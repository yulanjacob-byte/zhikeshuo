// ==================== 产品名称检测 ====================

/**
 * 检测文本中是否包含基金产品名称/代码
 * 用于合规拦截：不应对客发送具体产品推荐
 * @returns {string|null} 检测到的产品类型描述，null表示未检测到
 */
export function detectFundProduct(text) {
  if (!text || typeof text !== 'string') return null

  // 6位数字基金代码
  if (/\b\d{6}\b/.test(text)) return '基金代码'

  // 基金公司名称
  const companies = ['易方达', '华夏', '南方', '广发', '汇添富', '嘉实', '博时', '富国', '招商', '工银', '兴全', '中欧', '景顺', '交银', '银华', '鹏华', '国泰', '华安', '万家', '长城']
  for (const c of companies) {
    if (text.includes(c)) return `基金公司名称（${c}）`
  }

  // 基金类型关键词
  const fundTypes = ['基金A', '基金C', 'ETF联接', '指数A', '指数C', '混合A', '混合C', '股票型', '债券型']
  for (const t of fundTypes) {
    if (text.includes(t)) return `基金产品关键词（${t}）`
  }

  // 基金经理姓名（常见）
  const managers = ['张坤', '葛兰', '刘彦春', '谢治宇', '董承非', '傅鹏博', '朱少醒', '周蔚文']
  for (const m of managers) {
    if (text.includes(m)) return `基金经理姓名（${m}）`
  }

  return null
}

// ==================== 异议匹配 ====================

/**
 * 根据客户话语匹配异议处理话术
 * @param {string} text 客户情况描述
 * @returns {Object|null} 匹配到的异议 { title, reply, matchedKey }
 */
export function matchObjection(text) {
  if (!text || typeof text !== 'string') return null

  for (const obj of OBJECTIONS) {
    for (const key of obj.keys) {
      if (text.includes(key)) {
        return { title: obj.title, reply: obj.reply, matchedKey: key }
      }
    }
  }
  return null
}

