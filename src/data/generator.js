// ==================== 策略与禁忌构建 ====================

/**
 * 根据选中的标签构建经营策略与禁忌
 * @param {string[]} tagIds 选中的标签ID数组
 * @returns {{ strategies: Array, taboos: Array }}
 */
export function buildStrategy(tagIds) {
  const strategies = []
  const taboos = []
  const seen = new Set()

  if (!Array.isArray(tagIds) || tagIds.length === 0) {
    return { strategies, taboos }
  }

  for (const id of tagIds) {
    const tag = byId(id)
    if (!tag) continue

    if (tag.strategy && !seen.has('s_' + id)) {
      seen.add('s_' + id)
      strategies.push({
        tag: tag.name,
        text: tag.strategy
      })
    }

    if (tag.taboo && !seen.has('t_' + id)) {
      seen.add('t_' + id)
      taboos.push({
        tag: tag.name,
        text: tag.taboo
      })
    }
  }

  return { strategies, taboos }
}

// ==================== 本地生成引擎 ====================

/**
 * 本地话术生成引擎（API不可用时的降级方案）
 * @param {Object} params
 * @param {string} params.stageId - 沟通环节ID
 * @param {string} params.sceneId - 沟通渠道ID
 * @param {string[]} params.tagIds - 选中的标签ID数组
 * @param {string} params.context - 客户情况描述（选填）
 * @returns {{ script: string, matchInfo: string, objection: Object|null }}
 */
export function localGen(params) {
  const { stageId, sceneId, tagIds = [], context = '' } = params

  const stage = STAGES.find(s => s.id === stageId) || STAGES[0]
  const scene = SCENES.find(s => s.id === sceneId) || SCENES[0]

  const parts = []
  let matchInfo = ''

  // 1. 环节开场白
  if (stage.greet) {
    parts.push(stage.greet)
  }

  // 2. 异议匹配（如果客户有输入）
  const objection = matchObjection(context)
  if (objection) {
    parts.push(objection.reply)
    matchInfo = `已匹配异议：${objection.title}（关键词："${objection.matchedKey}"）`
  }

  // 3. 标签画像话术
  if (tagIds.length > 0) {
    const tagScripts = tagIds.slice(0, 6).map(id => {
      const tag = byId(id)
      return tag ? tag.script : null
    }).filter(Boolean)

    if (tagScripts.length > 0) {
      if (parts.length > 0 && !objection) parts.push('')
      parts.push(tagScripts.join('\n\n'))
    }

    if (!matchInfo) {
      const tagNames = tagIds.slice(0, 6).map(id => {
        const t = byId(id)
        return t ? t.name : id
      })
      matchInfo = `画像标签：${tagNames.join('、')}（${tagIds.length}个）`
    }
  }

  // 4. 环节收尾
  if (stage.next) {
    parts.push('')
    parts.push(stage.next)
  }

  // 5. 如果什么都没有，用话术库
  if (parts.length === 0) {
    const libs = matchLibrary(stageId, sceneId)
    if (libs.length > 0) {
      parts.push(libs[0].body)
      matchInfo = `参考话术：${libs[0].title}`
    } else {
      parts.push('XX总您好，我是您的理财经理。今天联系您主要是想了解一下您近期有没有理财方面的需求或者想法，我可以帮您做一些规划和建议。')
    }
  }

  // 6. RAG 检索：从手册中匹配相关段落
  const tagNames = tagIds.slice(0, 6).map(id => {
    const t = byId(id)
    return t ? t.name : ''
  }).filter(Boolean)
  const searchQuery = buildSearchQuery(tagNames, context, stageId)
  const sources = searchHandbook(searchQuery, { topK: 3, minScore: 2 })

  return {
    script: parts.join('\n\n'),
    matchInfo,
    objection,
    sources
  }
}

